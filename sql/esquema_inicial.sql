-- CHAMADA: CALL PROC_VERIFICAR_LICENCA(NULL, NULL, NULL, NULL);
CREATE OR REPLACE PROCEDURE PROC_VERIFICAR_LICENCA(
    OUT SUCESSO BOOLEAN,
    OUT RETORNO TEXT,
    OUT VALIDADE DATE,
    OUT MSG TEXT
)
LANGUAGE plpgsql
AS $$
DECLARE
    V_STATUS_SISTEMA TEXT;
    V_STATUS_LICENCA TEXT;
BEGIN
    SELECT C.STATUS_SISTEMA, C.STATUS_LICENCA, C.VALIDADE_LICENCA
    INTO V_STATUS_SISTEMA, V_STATUS_LICENCA, VALIDADE
    FROM TAB_CONFIG C
    WHERE C.ID_CONFIG = 1;

    SUCESSO := FALSE;

    IF NOT FOUND THEN
        RETORNO := 'CONFIG_AUSENTE';
        MSG := 'Configuracao do sistema nao encontrada.';
    ELSIF V_STATUS_SISTEMA = 'BLOQUEADO' THEN
        RETORNO := 'SISTEMA_BLOQUEADO';
        MSG := 'O sistema esta bloqueado.';
    ELSIF V_STATUS_SISTEMA = 'MANUTENCAO' THEN
        RETORNO := 'SISTEMA_EM_MANUTENCAO';
        MSG := 'O sistema esta em manutencao.';
    ELSIF V_STATUS_LICENCA = 'PENDENTE' THEN
        RETORNO := 'LICENCA_PENDENTE';
        MSG := 'A licenca ainda nao foi ativada.';
    ELSIF V_STATUS_LICENCA = 'BLOQUEADA' THEN
        RETORNO := 'LICENCA_BLOQUEADA';
        MSG := 'A licenca esta bloqueada.';
    ELSIF VALIDADE IS NULL THEN
        RETORNO := 'LICENCA_SEM_VALIDADE';
        MSG := 'A licenca nao tem data de validade.';
    ELSIF CURRENT_DATE > VALIDADE THEN
        RETORNO := 'LICENCA_EXPIRADA';
        MSG := 'A licenca expirou em ' || TO_CHAR(VALIDADE, 'DD/MM/YYYY') || '.';
    ELSE
        SUCESSO := TRUE;
        RETORNO := 'OK';
        MSG := 'Licenca valida.';
    END IF;
END;
$$;

