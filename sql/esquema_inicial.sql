-- CADASTRA ITEM DE ESTOQUE. UNIDADES SAO INDICATIVAS; AS QUANTIDADES SAO INFORMADAS MANUALMENTE.
-- EX.: PACOTE DE 1,5 KG: QTDE_COMPRA = 1500 G E QTDE_VENDA = 30 G POR PORCAO.
-- CUSTO_UNITARIO = CUSTO / QTDE_COMPRA * QTDE_VENDA. O CADASTRO NAO CRIA SALDO.
CREATE OR REPLACE PROCEDURE PROC_CADASTRAR_INSUMO(
    IN P_DESCRICAO TEXT,
    IN P_EAN TEXT,
    IN P_UM_COMPRA TEXT,
    IN P_QTDE_COMPRA NUMERIC,
    IN P_UM_VENDA TEXT,
    IN P_QTDE_VENDA NUMERIC,
    IN P_CUSTO TEXT,
    IN P_ESTOQUE_MINIMO NUMERIC,
    IN P_ESTOQUE_RECOMENDADO NUMERIC,
    IN P_CATEGORIA TEXT,
    IN P_MARCA TEXT,
    IN P_STATUS TEXT,
    IN P_ID_FORNECEDOR INT,
    IN P_CODIGO_FORNECEDOR TEXT,
    OUT SUCESSO BOOLEAN,
    OUT RETORNO TEXT,
    OUT MSG TEXT,
    OUT ID_INSUMO INT
)
LANGUAGE plpgsql
AS $$
DECLARE
    V_EAN TEXT := NULLIF(BTRIM(P_EAN), '');
    V_CODIGO_FORNECEDOR TEXT := NULLIF(BTRIM(P_CODIGO_FORNECEDOR), '');
    V_UM_COMPRA TEXT := UPPER(BTRIM(P_UM_COMPRA));
    V_UM_VENDA TEXT := UPPER(BTRIM(P_UM_VENDA));
    V_STATUS TEXT := COALESCE(UPPER(BTRIM(P_STATUS)), 'ATIVO');
    V_CUSTO_TEXTO TEXT := BTRIM(P_CUSTO);
    V_CUSTO NUMERIC;
    V_CUSTO_UNITARIO NUMERIC;
BEGIN
    SUCESSO := FALSE;
    ID_INSUMO := NULL;

    IF P_DESCRICAO IS NULL OR LENGTH(BTRIM(P_DESCRICAO)) NOT BETWEEN 1 AND 80
        OR P_DESCRICAO ~ '[[:cntrl:]]' THEN
        RETORNO := 'DESCRICAO_INVALIDA';
        MSG := 'Informe uma descricao de ate 80 caracteres, sem caracteres de controle.';
        RETURN;
    END IF;

    IF V_EAN IS NOT NULL AND NOT FN_GTIN_VALIDO(V_EAN) THEN
        RETORNO := 'EAN_INVALIDO';
        MSG := 'EAN/GTIN deve ter 8, 12, 13 ou 14 digitos e digito verificador valido.';
        RETURN;
    END IF;

    IF V_EAN IS NOT NULL AND EXISTS (SELECT 1 FROM TAB_INSUMOS WHERE EAN = V_EAN) THEN
        RETORNO := 'EAN_DUPLICADO';
        MSG := 'EAN/GTIN ja cadastrado.';
        RETURN;
    END IF;

    IF P_QTDE_COMPRA IS NULL OR P_QTDE_COMPRA <= 0 OR P_QTDE_COMPRA >= 100000000000
        OR P_QTDE_COMPRA <> ROUND(P_QTDE_COMPRA, 3)
        OR P_QTDE_VENDA IS NULL OR P_QTDE_VENDA <= 0 OR P_QTDE_VENDA >= 100000000000
        OR P_QTDE_VENDA <> ROUND(P_QTDE_VENDA, 3) THEN
        RETORNO := 'QUANTIDADE_INVALIDA';
        MSG := 'Quantidades devem ser positivas e ter no maximo tres casas decimais.';
        RETURN;
    END IF;

    IF NOT EXISTS (SELECT 1 FROM TAB_UNIDADES_MEDIDA
        WHERE SIGLA = V_UM_COMPRA AND NOT EXCLUIDO) THEN
        RETORNO := 'UNIDADE_COMPRA_INVALIDA';
        MSG := 'Unidade de compra nao cadastrada.';
        RETURN;
    END IF;

    IF NOT EXISTS (SELECT 1 FROM TAB_UNIDADES_MEDIDA
        WHERE SIGLA = V_UM_VENDA AND NOT EXCLUIDO) THEN
        RETORNO := 'UNIDADE_VENDA_INVALIDA';
        MSG := 'Unidade de consumo nao cadastrada.';
        RETURN;
    END IF;

    IF V_CUSTO_TEXTO IS NULL OR V_CUSTO_TEXTO !~ '^[0-9]{1,8}([.,][0-9]{1,2})?$' THEN
        RETORNO := 'CUSTO_INVALIDO';
        MSG := 'Custo deve ter no maximo duas casas decimais, sem separador de milhar.';
        RETURN;
    END IF;
    V_CUSTO := REPLACE(V_CUSTO_TEXTO, ',', '.')::NUMERIC;
    V_CUSTO_UNITARIO := ROUND(V_CUSTO / P_QTDE_COMPRA * P_QTDE_VENDA, 6);
    IF V_CUSTO_UNITARIO >= 100000000 THEN
        RETORNO := 'CUSTO_UNITARIO_INVALIDO';
        MSG := 'Custo da porcao excede o limite do campo.';
        RETURN;
    END IF;

    IF P_ESTOQUE_MINIMO IS NULL OR P_ESTOQUE_MINIMO < 0
        OR P_ESTOQUE_MINIMO >= 100000000000
        OR P_ESTOQUE_MINIMO <> ROUND(P_ESTOQUE_MINIMO, 3)
        OR P_ESTOQUE_RECOMENDADO IS NULL OR P_ESTOQUE_RECOMENDADO < P_ESTOQUE_MINIMO
        OR P_ESTOQUE_RECOMENDADO >= 100000000000
        OR P_ESTOQUE_RECOMENDADO <> ROUND(P_ESTOQUE_RECOMENDADO, 3) THEN
        RETORNO := 'ESTOQUE_ALVO_INVALIDO';
        MSG := 'Estoque recomendado deve ser maior ou igual ao minimo, com ate tres casas.';
        RETURN;
    END IF;

    IF V_STATUS NOT IN ('ATIVO', 'INATIVO') THEN
        RETORNO := 'STATUS_INVALIDO';
        MSG := 'Status deve ser ATIVO ou INATIVO.';
        RETURN;
    END IF;

    IF (P_CATEGORIA IS NOT NULL AND LENGTH(BTRIM(P_CATEGORIA)) > 80)
        OR (P_MARCA IS NOT NULL AND LENGTH(BTRIM(P_MARCA)) > 80) THEN
        RETORNO := 'TEXTO_LONGO';
        MSG := 'Categoria e marca devem ter ate 80 caracteres.';
        RETURN;
    END IF;

    IF (P_ID_FORNECEDOR IS NULL) <> (V_CODIGO_FORNECEDOR IS NULL)
        OR (V_CODIGO_FORNECEDOR IS NOT NULL AND
            (LENGTH(V_CODIGO_FORNECEDOR) > 80 OR V_CODIGO_FORNECEDOR ~ '[[:cntrl:]]')) THEN
        RETORNO := 'CODIGO_FORNECEDOR_INVALIDO';
        MSG := 'Informe fornecedor e codigo juntos; codigo deve ter ate 80 caracteres.';
        RETURN;
    END IF;

    IF P_ID_FORNECEDOR IS NOT NULL THEN
        IF NOT EXISTS (SELECT 1 FROM TAB_FORNECEDORES
            WHERE ID_FORNECEDOR = P_ID_FORNECEDOR AND NOT EXCLUIDO) THEN
            RETORNO := 'FORNECEDOR_INVALIDO';
            MSG := 'Fornecedor nao cadastrado ou excluido.';
            RETURN;
        END IF;
        IF EXISTS (SELECT 1 FROM TAB_FORNECEDOR_INSUMOS
            WHERE ID_FORNECEDOR = P_ID_FORNECEDOR
                AND CODIGO_FORNECEDOR = V_CODIGO_FORNECEDOR) THEN
            RETORNO := 'CODIGO_FORNECEDOR_DUPLICADO';
            MSG := 'Codigo ja utilizado por este fornecedor.';
            RETURN;
        END IF;
    END IF;

    INSERT INTO TAB_INSUMOS (
        EAN, DESCRICAO, UM_COMPRA, UM_VENDA, QTDE_COMPRA, QTDE_VENDA,
        CUSTO, CUSTO_MEDIO, CUSTO_UNITARIO, CATEGORIA, MARCA,
        ESTOQUE_MINIMO, ESTOQUE_RECOMENDADO, STATUS
    ) VALUES (
        V_EAN, BTRIM(P_DESCRICAO), V_UM_COMPRA, V_UM_VENDA, P_QTDE_COMPRA, P_QTDE_VENDA,
        V_CUSTO, 0, V_CUSTO_UNITARIO,
        NULLIF(BTRIM(P_CATEGORIA), ''), NULLIF(BTRIM(P_MARCA), ''),
        P_ESTOQUE_MINIMO, P_ESTOQUE_RECOMENDADO, V_STATUS
    ) RETURNING TAB_INSUMOS.ID_INSUMO INTO ID_INSUMO;

    IF P_ID_FORNECEDOR IS NOT NULL THEN
        INSERT INTO TAB_FORNECEDOR_INSUMOS (ID_FORNECEDOR, ID_INSUMO, CODIGO_FORNECEDOR)
        VALUES (P_ID_FORNECEDOR, ID_INSUMO, V_CODIGO_FORNECEDOR);
    END IF;

    SUCESSO := TRUE;
    RETORNO := 'OK';
    MSG := 'Insumo cadastrado com sucesso.';
END;
$$;

