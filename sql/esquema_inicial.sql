CREATE OR REPLACE FUNCTION FN_GTIN_VALIDO(P_GTIN TEXT)
RETURNS BOOLEAN
LANGUAGE plpgsql
IMMUTABLE
AS $$
DECLARE
    V_SOMA INT := 0;
    V_POS INT;
    V_TAMANHO INT;
BEGIN
    IF P_GTIN IS NULL OR P_GTIN !~ '^[0-9]+$'
        OR LENGTH(P_GTIN) NOT IN (8, 12, 13, 14) THEN
        RETURN FALSE;
    END IF;

    V_TAMANHO := LENGTH(P_GTIN);
    FOR V_POS IN 1..V_TAMANHO - 1 LOOP
        V_SOMA := V_SOMA + SUBSTRING(P_GTIN FROM V_POS FOR 1)::INT
            * CASE WHEN (V_TAMANHO - V_POS) % 2 = 1 THEN 3 ELSE 1 END;
    END LOOP;

    RETURN (10 - V_SOMA % 10) % 10 = RIGHT(P_GTIN, 1)::INT;
END;
$$;

