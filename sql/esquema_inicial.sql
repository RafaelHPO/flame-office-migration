CREATE OR REPLACE PROCEDURE PROC_CADASTRAR_USUARIO(
    IN P_NOME TEXT,
    IN P_LOGIN TEXT,
    IN P_SENHA TEXT,
    IN P_SETOR TEXT,
    IN P_STATUS TEXT,
    OUT SUCESSO BOOLEAN,
    OUT RETORNO TEXT,
    OUT MSG TEXT,
    OUT ID_USUARIO INT
)
LANGUAGE plpgsql
AS $$
DECLARE
    V_LOGIN TEXT := UPPER(BTRIM(P_LOGIN));
    V_SETOR TEXT := UPPER(BTRIM(P_SETOR));
    V_STATUS TEXT := COALESCE(UPPER(BTRIM(P_STATUS)), 'ATIVO');
BEGIN
    SUCESSO := FALSE;
    ID_USUARIO := NULL;

    IF P_NOME IS NULL OR LENGTH(BTRIM(P_NOME)) NOT BETWEEN 1 AND 80
        OR P_NOME ~ '[[:cntrl:]]' THEN
        RETORNO := 'NOME_INVALIDO';
        MSG := 'Nome deve ter de 1 a 80 caracteres, sem caracteres de controle.';
        RETURN;
    END IF;

    IF V_LOGIN IS NULL OR LENGTH(V_LOGIN) NOT BETWEEN 3 AND 40
        OR V_LOGIN !~ '^[A-Z0-9._@-]+$' THEN
        RETORNO := 'LOGIN_INVALIDO';
        MSG := 'Login deve ter de 3 a 40 caracteres e conter apenas letras, numeros, ponto, arroba, hifen ou sublinhado.';
        RETURN;
    END IF;

    IF EXISTS (SELECT 1 FROM TAB_USUARIOS WHERE UPPER(LOGIN) = V_LOGIN) THEN
        RETORNO := 'LOGIN_DUPLICADO';
        MSG := 'Login ja cadastrado.';
        RETURN;
    END IF;

    IF P_SENHA IS NULL OR OCTET_LENGTH(P_SENHA) NOT BETWEEN 4 AND 72
        OR BTRIM(P_SENHA) = '' OR P_SENHA ~ '[[:cntrl:]]' THEN
        RETORNO := 'SENHA_INVALIDA';
        MSG := 'Senha deve ter de 4 a 72 bytes e nao pode ser vazia ou conter caracteres de controle.';
        RETURN;
    END IF;

    IF V_SETOR IS NULL OR V_SETOR NOT IN ('FINANCEIRO', 'ESTOQUE', 'MARKETING', 'GERAL') THEN
        RETORNO := 'SETOR_INVALIDO';
        MSG := 'Setor invalido.';
        RETURN;
    END IF;

    IF V_STATUS NOT IN ('ATIVO', 'INATIVO') THEN
        RETORNO := 'STATUS_INVALIDO';
        MSG := 'Status deve ser ATIVO ou INATIVO.';
        RETURN;
    END IF;

    INSERT INTO TAB_USUARIOS (NOME, LOGIN, SENHA_HASH, SETOR, STATUS)
    VALUES (BTRIM(P_NOME), V_LOGIN, CRYPT(P_SENHA, GEN_SALT('bf')), V_SETOR, V_STATUS)
    RETURNING TAB_USUARIOS.ID_USUARIO INTO ID_USUARIO;

    SUCESSO := TRUE;
    RETORNO := 'OK';
    MSG := 'Usuario cadastrado com sucesso.';
EXCEPTION
    WHEN unique_violation THEN
        SUCESSO := FALSE;
        ID_USUARIO := NULL;
        RETORNO := 'LOGIN_DUPLICADO';
        MSG := 'Login ja cadastrado.';
END;
$$;

-- CHAMADA: CALL PROC_LOGIN('login', 'senha', NULL, NULL, NULL, NULL);
CREATE OR REPLACE PROCEDURE PROC_LOGIN(
    IN P_USUARIO TEXT,
    IN P_SENHA TEXT,
    OUT RETORNO TEXT,
    OUT ID_USUARIO INT,
    OUT USUARIO TEXT,
    OUT SETOR TEXT
)
LANGUAGE plpgsql
AS $$
DECLARE
    V_ID_USUARIO INT;
    V_USUARIO TEXT;
    V_SETOR TEXT;
    V_STATUS TEXT;
    V_SENHA_HASH TEXT;
    V_LIBERAUSUARIO SMALLINT := 0;
    V_LIBERASENHA SMALLINT := 0;
BEGIN
    ID_USUARIO := NULL;
    USUARIO := NULL;
    SETOR := NULL;

    SELECT U.ID_USUARIO, U.LOGIN, U.SETOR, U.STATUS
    INTO V_ID_USUARIO, V_USUARIO, V_SETOR, V_STATUS
    FROM TAB_USUARIOS U
    WHERE UPPER(U.LOGIN) = UPPER(BTRIM(P_USUARIO))
        AND NOT U.EXCLUIDO;

    IF FOUND THEN
        V_LIBERAUSUARIO := 1;
    END IF;

    SELECT U.SENHA_HASH INTO V_SENHA_HASH
    FROM TAB_USUARIOS U
    WHERE U.ID_USUARIO = V_ID_USUARIO
        AND OCTET_LENGTH(P_SENHA) <= 72
        AND U.SENHA_HASH = CRYPT(P_SENHA, U.SENHA_HASH);

    IF FOUND THEN
        V_LIBERASENHA := 1;
    END IF;

    IF V_LIBERAUSUARIO = 0 AND V_LIBERASENHA = 0 THEN
        RETORNO := 'USUARIO_INVALIDO';
        RETURN;
    ELSIF V_LIBERAUSUARIO = 0 AND V_LIBERASENHA = 1 THEN
        RETORNO := 'USUARIO_OU_SENHA_INVALIDOS';
        RETURN;
    ELSIF V_LIBERAUSUARIO = 1 AND V_LIBERASENHA = 0 THEN
        RETORNO := 'SENHA_INVALIDA';
        RETURN;
    END IF;

    IF V_STATUS = 'INATIVO' THEN
        RETORNO := 'USUARIO_INATIVO';
        RETURN;
    END IF;

    RETORNO := 'OK';
    ID_USUARIO := V_ID_USUARIO;
    USUARIO := V_USUARIO;
    SETOR := V_SETOR;
END;
$$;

