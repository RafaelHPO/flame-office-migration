    DESCRICAO TEXT UNIQUE NOT NULL CHECK (LENGTH(BTRIM(DESCRICAO)) BETWEEN 1 AND 80),
    CATEGORIA TEXT,
    CMV NUMERIC(10,2),
    PRECO_VENDA NUMERIC(10,2) NOT NULL CHECK (PRECO_VENDA > 0),
    STATUS TEXT NOT NULL DEFAULT 'ATIVO' CHECK (STATUS IN ('ATIVO', 'INATIVO')),
    EXCLUIDO BOOLEAN NOT NULL DEFAULT FALSE
);

-- PRODUTO VENDAVEL: INSUMOS, QUANTIDADES E CONVERSOES SAO CADASTRADOS SEPARADAMENTE.
CREATE OR REPLACE PROCEDURE PROC_CADASTRAR_PRODUTO(
    IN P_DESCRICAO TEXT,
    IN P_CATEGORIA TEXT,
    IN P_PRECO_VENDA TEXT,
    IN P_STATUS TEXT,
    OUT SUCESSO BOOLEAN,
    OUT RETORNO TEXT,
    OUT MSG TEXT,
    OUT ID_PRODUTO INT
)
LANGUAGE plpgsql
AS $$
DECLARE
    V_PRECO_TEXTO TEXT := BTRIM(P_PRECO_VENDA);
    V_PRECO NUMERIC;
    V_STATUS TEXT := COALESCE(UPPER(BTRIM(P_STATUS)), 'ATIVO');
BEGIN
    SUCESSO := FALSE;
    ID_PRODUTO := NULL;

    IF P_DESCRICAO IS NULL OR LENGTH(BTRIM(P_DESCRICAO)) NOT BETWEEN 1 AND 80
        OR P_DESCRICAO ~ '[[:cntrl:]]' THEN
        RETORNO := 'DESCRICAO_INVALIDA';
        MSG := 'Informe uma descricao de ate 80 caracteres, sem caracteres de controle.';
        RETURN;
    END IF;

    IF EXISTS (SELECT 1 FROM TAB_PRODUTOS
        WHERE LOWER(BTRIM(DESCRICAO)) = LOWER(BTRIM(P_DESCRICAO))) THEN
        RETORNO := 'PRODUTO_DUPLICADO';
        MSG := 'Produto ja cadastrado.';
        RETURN;
    END IF;

    IF P_CATEGORIA IS NOT NULL AND LENGTH(BTRIM(P_CATEGORIA)) > 80 THEN
        RETORNO := 'CATEGORIA_INVALIDA';
        MSG := 'Categoria deve ter ate 80 caracteres.';
        RETURN;
    END IF;

    IF V_PRECO_TEXTO IS NULL OR V_PRECO_TEXTO !~ '^[0-9]{1,8}([.,][0-9]{1,2})?$' THEN
        RETORNO := 'PRECO_INVALIDO';
        MSG := 'Preco deve ter no maximo duas casas decimais, sem separador de milhar.';
        RETURN;
    END IF;
    V_PRECO := REPLACE(V_PRECO_TEXTO, ',', '.')::NUMERIC;
    IF V_PRECO <= 0 THEN
        RETORNO := 'PRECO_INVALIDO';
        MSG := 'Preco deve ser maior que zero.';
        RETURN;
    END IF;

    IF V_STATUS NOT IN ('ATIVO', 'INATIVO') THEN
        RETORNO := 'STATUS_INVALIDO';
        MSG := 'Status deve ser ATIVO ou INATIVO.';
        RETURN;
    END IF;

    INSERT INTO TAB_PRODUTOS (DESCRICAO, CATEGORIA, PRECO_VENDA, STATUS)
    VALUES (BTRIM(P_DESCRICAO), NULLIF(BTRIM(P_CATEGORIA), ''), V_PRECO, V_STATUS)
    RETURNING TAB_PRODUTOS.ID_PRODUTO INTO ID_PRODUTO;

    SUCESSO := TRUE;
    RETORNO := 'OK';
    MSG := 'Produto cadastrado com sucesso.';
END;
$$;

